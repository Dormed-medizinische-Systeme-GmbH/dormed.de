  document.querySelectorAll('.gb-faq__question').forEach(function(btn) {
    btn.addEventListener('click', function() {
      var item = btn.closest('.gb-faq__item');
      var isOpen = item.classList.contains('gb-faq__item--open');
      document.querySelectorAll('.gb-faq__item--open').forEach(function(el) {
        el.classList.remove('gb-faq__item--open');
        el.querySelector('.gb-faq__question').setAttribute('aria-expanded', 'false');
      });
      if (!isOpen) {
        item.classList.add('gb-faq__item--open');
        btn.setAttribute('aria-expanded', 'true');
      }
    });
  });
})();
