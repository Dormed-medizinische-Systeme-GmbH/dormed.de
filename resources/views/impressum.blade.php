(function() {
  // Accordion
  var triggers = document.querySelectorAll('.imp__acc-trigger');
  triggers.forEach(function(btn) {
    btn.addEventListener('click', function() {
      var expanded = btn.getAttribute('aria-expanded') === 'true';
      var bodyId = btn.getAttribute('aria-controls');
      var body = document.getElementById(bodyId);

      // Close all others
      triggers.forEach(function(other) {
        if (other !== btn) {
          other.setAttribute('aria-expanded', 'false');
          var otherId = other.getAttribute('aria-controls');
          var otherBody = document.getElementById(otherId);
          if (otherBody) otherBody.classList.remove('imp__acc-open');
        }
      });

      // Toggle this one
      btn.setAttribute('aria-expanded', String(!expanded));
      if (body) body.classList.toggle('imp__acc-open', !expanded);
    });
  });

  // Scroll animations
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) {
        e.target.classList.add('imp__vis');
        obs.unobserve(e.target);
      }
    });
  }, { threshold: 0.08, rootMargin: '0px 0px -20px 0px' });

  document.querySelectorAll('.imp__anim').forEach(function(el) {
    obs.observe(el);
  });
})();
</script>
